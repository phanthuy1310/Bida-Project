    public void Update(){
        selectedRow = tableCategory.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng để cập nhật", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String _textCategoryName = textCategoryName.getText();
        String _textCategoryStatus = textCategoryStatus.getText();

        if (_textCategoryName.isEmpty() || _textCategoryStatus.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Bạn cần điền đầy đủ thông tin", "Lỗi", JOptionPane.ERROR_MESSAGE);
        } 
        else {
            try {
                // Lấy ID của hàng đã chọn
                int categoryId = (int) tableCategory.getValueAt(selectedRow, 0);

                Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);
                PreparedStatement stmt = conn.prepareStatement("UPDATE category SET categoryName = ?, status = ? WHERE categoryID = ?");
                
                // Truyền các giá trị vào dấu ?
                stmt.setString(1, _textCategoryName);
                stmt.setString(2, _textCategoryStatus);
                stmt.setInt(3, categoryId);

                int effectedRows = stmt.executeUpdate();
                if (effectedRows > 0) {
                    JOptionPane.showMessageDialog(this, "Đã cập nhật thành công");
                    // Gọi lại hàm Read để đổ dữ liệu mới vào bảng
                    read();
                    textCategoryName.setText("");
                    textCategoryStatus.setText("");
                } 
                else {
                    JOptionPane.showMessageDialog(this, "Cập nhật thất bại", "Lỗi", JOptionPane.ERROR_MESSAGE);
                }
                stmt.close();
                conn.close();
            } 
            catch (SQLException e) {
                e.printStackTrace();
            }
        }       
    }
