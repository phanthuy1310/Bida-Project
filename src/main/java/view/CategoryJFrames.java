    private void Delete() {
        selectedRow = tableCategory.getSelectedRow();

        // Kiểm tra xem có dòng nào được chọn không
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn danh mục cần xóa!");
            return;
        }

        // Lấy categoryId từ bảng (giả sử cột 0 chứa categoryId)
        int categoryId = Integer.parseInt(tableCategory.getValueAt(selectedRow, 0).toString());

        // Xác nhận xóa
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Bạn có chắc chắn muốn xóa danh mục này và tất cả các dịch vụ liên quan?", 
            "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        Connection conn = null;
        PreparedStatement stmt1 = null;
        PreparedStatement stmt2 = null;

        try {
            conn = DriverManager.getConnection(URL,USER,PASSWORD);
            conn.setAutoCommit(false); // Bắt đầu transaction

            // Xóa tất cả các dịch vụ (service) có categoryId trùng
            String deleteServicesSQL = "DELETE FROM serviceitem WHERE categoryID = ?";
            stmt1 = conn.prepareStatement(deleteServicesSQL);
            stmt1.setInt(1, categoryId);
            stmt1.executeUpdate();

            // Xóa danh mục (category)
            String deleteCategorySQL = "DELETE FROM category WHERE categoryID = ?";
            stmt2 = conn.prepareStatement(deleteCategorySQL);
            stmt2.setInt(1, categoryId);
            int rowsDeleted = stmt2.executeUpdate();

            if (rowsDeleted > 0) {
                conn.commit(); // Xác nhận transaction
                JOptionPane.showMessageDialog(this, "Xóa danh mục và tất cả dịch vụ liên quan thành công!");
                loadCategoryTable(); // Cập nhật lại bảng danh mục
                textCategoryName.setText("");
                textCategoryStatus.setText("");
            } else {
                conn.rollback();
                JOptionPane.showMessageDialog(this, "Xóa thất bại. Vui lòng thử lại.");
            }

        } catch (SQLException e) {
            if (conn != null) {
                try {
                    conn.rollback(); // Hoàn tác nếu có lỗi
                } catch (SQLException rollbackEx) {
                    rollbackEx.printStackTrace();
                }
            }
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi xóa danh mục: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (stmt1 != null) stmt1.close();
                if (stmt2 != null) stmt2.close();
                if (conn != null) conn.close();
            } catch (SQLException closeEx) {
                closeEx.printStackTrace();
            }
        }
    }
    private void loadCategoryTable() {
        DefaultTableModel model = (DefaultTableModel) tableCategory.getModel();
        model.setRowCount(0); // Xóa dữ liệu cũ trước khi cập nhật mới

        Connection conn = null;
        Statement stmt = null;
        ResultSet rs = null;

        try {
            conn = DriverManager.getConnection(URL,USER,PASSWORD);
            stmt = conn.createStatement();
            rs = stmt.executeQuery("SELECT * FROM category"); // Lấy danh sách danh mục từ database

            while (rs.next()) {
                int id = rs.getInt("categoryID");
                String name = rs.getString("categoryName");
                String status = rs.getString("status");
                model.addRow(new Object[]{id, name,status}); // Thêm vào bảng
            }

        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi tải danh mục: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        } finally {
            try {
                if (rs != null) rs.close();
                if (stmt != null) stmt.close();
                if (conn != null) conn.close();
            } catch (SQLException ex) {
                ex.printStackTrace();
            }
        }
    }



