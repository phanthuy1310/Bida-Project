    public void Create() {
        String _textCategoryName = textCategoryName.getText().trim();
        String _textCategoryStatus = textCategoryStatus.getText().trim();

        if (_textCategoryName.isEmpty() || _textCategoryStatus.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Bạn cần điền đầy đủ thông tin", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            Connection conn = DriverManager.getConnection(URL, USER, PASSWORD);

            // Kiểm tra categoryName đã tồn tại chưa
            PreparedStatement checkStmt = conn.prepareStatement("SELECT COUNT(*) FROM category WHERE categoryName = ?");
            checkStmt.setString(1, _textCategoryName);
            ResultSet rs = checkStmt.executeQuery();
            rs.next();
            int count = rs.getInt(1);
            rs.close();
            checkStmt.close();

            if (count > 0) {
                JOptionPane.showMessageDialog(this, "Đã có loại dịch vụ này!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            } else {
                // Thêm mới nếu không trùng
                PreparedStatement stmt = conn.prepareStatement("INSERT INTO category (categoryName, status) VALUES (?, ?)");
                stmt.setString(1, _textCategoryName);
                stmt.setString(2, _textCategoryStatus);
                int effectedRows = stmt.executeUpdate();
                stmt.close();

                if (effectedRows > 0) {
                    JOptionPane.showMessageDialog(this, "Đã thêm bản ghi thành công");
                    read(); // Cập nhật lại bảng
                    textCategoryName.setText("");
                    textCategoryStatus.setText("");
                }
            }
            conn.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
